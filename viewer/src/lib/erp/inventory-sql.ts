import 'server-only';
import { INVENTORY_COLUMNS } from './inventory-read';
const requested=`R AS (SELECT DISTINCT COLUMN1 AS STYLECD FROM VALUES ${Array(10).fill('(?)').join(',')}),
M AS (SELECT STYLECD,COUNT(*) AS MASTER_ROWS,COUNT(DISTINCT BRANDCD) AS BRAND_COUNT,MIN(BRANDCD) AS BRANDCD
FROM BCAVE.SEWON.SW_STYLEINFO WHERE STYLECD IN (SELECT STYLECD FROM R) GROUP BY STYLECD)`;
const match='m.MASTER_ROWS=1 AND m.BRAND_COUNT=1 AND m.BRANDCD=b.BRANDCD';
function sql(table:string,location:string,quantities:readonly string[]){return `WITH B AS (SELECT ? AS BRANDCD),${requested}
SELECT r.STYLECD,CASE WHEN ${match} THEN m.BRANDCD ELSE NULL END AS MAPPED_BRAND,
COALESCE(m.MASTER_ROWS,0) AS MASTER_ROWS,COALESCE(m.BRAND_COUNT,0) AS BRAND_COUNT,
CASE WHEN m.STYLECD IS NULL THEN 'MISSING' WHEN m.BRAND_COUNT>1 THEN 'CONFLICT' WHEN m.MASTER_ROWS<>1 THEN 'DUPLICATE' WHEN m.BRAND_COUNT=0 THEN 'UNKNOWN' WHEN m.BRANDCD<>b.BRANDCD THEN 'OUT_OF_SCOPE' ELSE 'MATCHED' END AS MAPPING,
CASE WHEN i.STYLECD IS NULL THEN 0 ELSE 1 END AS SOURCE_PRESENT,
COUNT(i.STYLECD) OVER(PARTITION BY r.STYLECD) AS STYLE_SOURCE_ROWS,
CASE WHEN ${match} THEN i.${location} ELSE NULL END AS LOCATIONCD,
CASE WHEN ${match} THEN i.COLORCD ELSE NULL END AS COLORCD,CASE WHEN ${match} THEN i.SIZECD ELSE NULL END AS SIZECD,
CASE WHEN i.STYLECD IS NULL THEN 0 ELSE COUNT(*) OVER(PARTITION BY r.STYLECD,i.${location},i.COLORCD,i.SIZECD) END AS DUPLICATE_GRAIN,
${quantities.map(q=>`CASE WHEN ${match} THEN i.${q} ELSE NULL END AS ${q}`).join(',')}
FROM R r CROSS JOIN B b LEFT JOIN M m ON r.STYLECD=m.STYLECD
LEFT JOIN BCAVE.SEWON.${table} i ON r.STYLECD=i.STYLECD
ORDER BY r.STYLECD,LOCATIONCD,COLORCD,SIZECD LIMIT 201`;}
export const INVENTORY_SQL={shop:sql('SW_SHOPINV','SHOPCD',INVENTORY_COLUMNS.shop),warehouse:sql('SW_WHINV','WHCD',INVENTORY_COLUMNS.warehouse)} as const;
